def unlock(t, match, docs_, stage=1, req=None, blocked=None, speaker=None):
    r = {"type": t, "match": match, "unlock": docs_ if isinstance(docs_, list) else [docs_], "stage": stage}
    if req: r["requires_any"] = req
    if blocked: r["blocked"] = blocked
    if speaker: r["speaker"] = speaker
    rules.append(r)


def resp(t, match, who, text, stage=1, before=None, req=None, blocked=None):
    r = {"type": t, "match": match, "stage": stage, "response": say(who, text), "speaker": who}
    if before: r["before_stage"] = before
    if req: r["requires_any"] = req
    if blocked: r["blocked"] = blocked
    rules.append(r)


